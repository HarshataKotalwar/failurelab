class InvestigatorProviderError(ValueError):
    """A configured provider could not return a trustworthy assessment."""


class TransientGeminiError(InvestigatorProviderError):
    """Gemini was temporarily unavailable before returning a response."""


class GeminiAffectedService(BaseModel):
    model_config = ConfigDict(extra="forbid")

    service: str
    impact: Literal["direct", "indirect"]
    evidence_ids: list[str] = Field(max_length=30)


class GeminiAssessment(BaseModel):
    """Untrusted, structured model claims; system-owned metadata is excluded."""

    model_config = ConfigDict(extra="forbid")

    outcome: Literal["root_cause_identified", "insufficient_evidence"]
    root_cause: str | None = Field(max_length=1000)
    root_cause_evidence_ids: list[str] = Field(max_length=30)
    affected_services: list[GeminiAffectedService] = Field(max_length=20)
    timeline_evidence_ids: list[str] = Field(max_length=100)
    confidence_rationale: str = Field(max_length=1000)
    recommended_action: str = Field(max_length=1000)
    recommended_action_evidence_ids: list[str] = Field(max_length=30)
    missing_evidence: list[str] = Field(max_length=30)
    limitations: list[str] = Field(max_length=30)


